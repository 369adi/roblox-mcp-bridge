// Build: bundles the extension (MV3) and the bridge (single zero-dependency file).
// Usage: npm run build
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PROVIDERS } from "../shared/src/providers.ts";
// Version: package.json is the single source of truth. protocol.ts (bundled into extension + bridge)
// and VERSION.txt are rewritten from it on every build.
const __root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PKG_VERSION = JSON.parse(fs.readFileSync(path.join(__root, "package.json"), "utf8")).version;
{
  const protoFile = path.join(__root, "shared", "src", "protocol.ts");
  const src = fs.readFileSync(protoFile, "utf8");
  const next = src.replace(/export const BRIDGE_VERSION = "[^"]*";/, `export const BRIDGE_VERSION = "${PKG_VERSION}";`);
  if (next !== src) fs.writeFileSync(protoFile, next);
  fs.writeFileSync(path.join(__root, "VERSION.txt"), `Brickwire ${PKG_VERSION}\nbuilt ${new Date().toISOString()}\n`);
}
const BRIDGE_VERSION = PKG_VERSION;
import { packLibrary, minifyLuau } from "../shared/src/library/pack.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const extOut = path.join(root, "extension", "dist");
const bridgeOut = path.join(root, "bridge", "dist");
fs.rmSync(extOut, { recursive: true, force: true });
fs.rmSync(bridgeOut, { recursive: true, force: true });
fs.mkdirSync(extOut, { recursive: true });
fs.mkdirSync(bridgeOut, { recursive: true });

// Luau helper library → generated TS module (single source of truth: shared/src/bw-helpers.luau)
{
  // minified (comments/indentation stripped, embedded script sources kept verbatim) → ~40% smaller execute_luau payloads
  const lua = minifyLuau(fs.readFileSync(path.join(root, "shared", "src", "bw-helpers.luau"), "utf8").replace(/\r/g, ""));
  const ts = "// GENERATED by scripts/build.mjs from bw-helpers.luau — do not edit.\nexport const BW_HELPERS_LUAU: string = " + JSON.stringify(lua) + ";\n";
  fs.writeFileSync(path.join(root, "shared", "src", "bw-helpers.generated.ts"), ts);
  // resource library (kits + icons + catalog data) → injected only when the code uses BW.kit/kits/icon/furnish
  const lib = packLibrary(fs.readFileSync(path.join(root, "shared", "src", "library", "bw-library.luau"), "utf8"));
  const libTs = "// GENERATED by scripts/build.mjs from library/bw-library.luau + icons.ts + catalog.ts — do not edit.\nexport const BW_LIBRARY_LUAU: string = " + JSON.stringify(lib) + ";\n";
  fs.writeFileSync(path.join(root, "shared", "src", "library", "bw-library.generated.ts"), libTs);
  // asset-pack runtime (BW.asset) → injected only when the code uses BW.asset / BW.assetInfo
  const assets = minifyLuau(fs.readFileSync(path.join(root, "shared", "src", "library", "bw-assets.luau"), "utf8"));
  fs.writeFileSync(path.join(root, "shared", "src", "library", "bw-assets.generated.ts"), "// GENERATED by scripts/build.mjs from library/bw-assets.luau — do not edit.\nexport const BW_ASSETS_LUAU: string = " + JSON.stringify(assets) + ";\n");
}
if (!fs.existsSync(path.join(root, "packs", "built"))) throw new Error("packs/built missing — run: node --import tsx scripts/gen-packs.ts");

const common = { bundle: true, target: ["chrome116"], sourcemap: false, legalComments: "none", logLevel: "warning" };
await build({ ...common, entryPoints: { content: "extension/src/content.ts" }, outdir: extOut, format: "iife" });
await build({ ...common, entryPoints: { keepawake: "extension/src/keepawake.ts" }, outdir: extOut, format: "iife" });
await build({ ...common, entryPoints: { background: "extension/src/background.ts" }, outdir: extOut, format: "iife" });
await build({ ...common, entryPoints: { popup: "extension/src/popup/popup.ts", options: "extension/src/options/options.ts" }, outdir: extOut, format: "iife" });

const pub = path.join(root, "extension", "public");
fs.cpSync(pub, extOut, { recursive: true });

const hosts = [...new Set(PROVIDERS.flatMap((p) => p.hosts))];
const manifest = {
  manifest_version: 3,
  name: "Brickwire — Roblox Agent",
  short_name: "Brickwire",
  version: BRIDGE_VERSION,
  description: "Turns Notion AI, DeepSeek, ChatGPT, Claude, Gemini, Grok, Qwen, Kimi, GLM, Mistral, Perplexity, Copilot, Poe, Arena (or any chat site you add) into a Roblox Studio agent.",
  minimum_chrome_version: "116",
  icons: { 16: "icons/icon16.png", 32: "icons/icon32.png", 48: "icons/icon48.png", 128: "icons/icon128.png" },
  action: { default_popup: "popup.html", default_title: "Roblox Agent", default_icon: { 16: "icons/icon16.png", 32: "icons/icon32.png" } },
  options_page: "options.html",
  background: { service_worker: "background.js" },
  permissions: ["storage", "scripting"],
  optional_host_permissions: ["https://*/*"],
  // ui-resources.com: Library → Community catalogue + thumbnails (fetched by the service worker only)
  host_permissions: ["http://127.0.0.1/*", "http://localhost/*", "https://ui-resources.com/*", "https://uiassets.commissiontoolz.xyz/*"],
  content_scripts: [{ matches: hosts.map((h) => `https://${h}/*`), js: ["content.js"], run_at: "document_idle", all_frames: false },
    // keep-awake: page believes the tab is visible/focused (MAIN world, before the site's scripts)
    { matches: hosts.map((h) => `https://${h}/*`), js: ["keepawake.js"], run_at: "document_start", world: "MAIN", all_frames: false }],
  // Library previews (SVG) are fetched lazily by the panel; custom sites can be any https host.
  web_accessible_resources: [{ resources: ["library/previews.json", "library/community.json", "library/packs.json", "library/packs/*", "paint.html", "paint.js"], matches: ["https://*/*"] }],
};
if (!fs.existsSync(path.join(extOut, "library", "previews.json"))) throw new Error("extension/public/library/previews.json missing — run: node --import tsx scripts/gen-library.ts");
fs.writeFileSync(path.join(extOut, "manifest.json"), JSON.stringify(manifest, null, 2));
// Paint inside the chat page: MV3 extension pages forbid inline <script> and on*= handlers,
// so the bridge page is split into paint.html + paint.js and handlers become addEventListener (no eval).
{
  let html = fs.readFileSync(path.join(root, "bridge", "src", "paint.html"), "utf8");
  const m = html.match(/<script>([\s\S]*?)<\/script>/);
  if (!m) throw new Error("paint.html: inline script not found");
  let n = 0;
  const binds = [];
  html = html.replace(m[0], '<script src="paint.js"></script>');
  html = html.replace(/\son(click|change|input)="([^"]*)"/g, (_s, ev, code) => { const k = n++; binds.push(`document.querySelector('[data-bwh="${k}"]').addEventListener("${ev}",function(event){${code.replace(/&quot;/g, '"')}});`); return ` data-bwh="${k}"`; });
  if (/\son[a-z]+="/.test(html.replace(/<script[\s\S]*?<\/script>/g, ""))) throw new Error("paint.html: unconverted inline handler");
  const js = m[1] + "\n;(function(){" + binds.join("\n") + "})();\n";
  fs.writeFileSync(path.join(extOut, "paint.html"), html);
  fs.writeFileSync(path.join(extOut, "paint.js"), js);
}

await build({
  ...common,
  target: ["node20"],
  platform: "node",
  format: "esm",
  entryPoints: ["bridge/src/index.ts"],
  outfile: path.join(bridgeOut, "bridge.mjs"),
  banner: { js: "// Brickwire Bridge — bundled, no runtime dependencies. Run: node bridge/dist/bridge.mjs" },
});
fs.copyFileSync(path.join(root, "bridge", "src", "dashboard.html"), path.join(bridgeOut, "dashboard.html"));
fs.copyFileSync(path.join(root, "bridge", "src", "ui-builder.html"), path.join(bridgeOut, "ui-builder.html"));
fs.copyFileSync(path.join(root, "bridge", "src", "app.html"), path.join(bridgeOut, "app.html"));
fs.copyFileSync(path.join(root, "bridge", "src", "paint.html"), path.join(bridgeOut, "paint.html"));
for (const f of ["i18n.js","workspace-ui.js","workspace.css","app-depth.css","app-depth.js","scene3d.js","animation-editor.js","app-skills-ui.js","app-skills.css","app-runtime-ui.js","app-mcp-ui.js","app-mcp.css","mcp.html","bw3-ui.js","bw3.css","attachments-ui.js","motion-ui.js","motion.css"]) fs.copyFileSync(path.join(root,"bridge","src",f),path.join(bridgeOut,f));
fs.cpSync(path.join(root,"bridge","src","fonts"),path.join(bridgeOut,"fonts"),{recursive:true});
fs.cpSync(path.join(root,"bridge","skills"),path.join(bridgeOut,"skills"),{recursive:true});
await import("./make-rbxmx.mjs");
const size = (f) => (fs.statSync(f).size / 1024).toFixed(1) + " KB";
console.log(`extension/dist: content.js ${size(path.join(extOut, "content.js"))}, background.js ${size(path.join(extOut, "background.js"))}; ${hosts.length} host patterns`);
console.log(`bridge/dist/bridge.mjs ${size(path.join(bridgeOut, "bridge.mjs"))}`);
